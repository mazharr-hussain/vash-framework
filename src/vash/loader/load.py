"""Clean-slate loader (C-13)."""
import shutil
import os
from dataclasses import dataclass
from pathlib import Path
from typing import Any
from vash.core.freeze import load_freeze
from vash.core.paths import vash_root

@dataclass(frozen=True)
class LoadReport:
    written: list[str]
    removed: list[str]
    warnings: list[str]

def generate_claude_md(repo_root: Path) -> str:
    """Generate CLAUDE.md from laws.md and project-stack.json."""
    try:
        freeze = load_freeze(repo_root)
        laws_path = vash_root() / "method" / "laws.md"
        laws = laws_path.read_text(encoding="utf-8") if laws_path.exists() else ""
    except Exception:
        laws = "# VASH Laws\n(not found)"
        freeze = None

    lines = ["# CLAUDE.md", "", "This file is generated by VASH. Do not edit by hand.", ""]
    lines.append("## Project Stack")
    if freeze:
        lines.append(f"- **Stack Pack**: {freeze.pack[0]} v{freeze.pack[1]}")
        lines.append(f"- **Forge**: {freeze.forge[0]}")
        lines.append(f"- **CI**: {freeze.ci[0]}")
        lines.append(f"- **Cloud**: {freeze.cloud[0]}")
        lines.append(f"- **Floor**: {freeze.floor}")
    else:
        lines.append("- (No valid project-stack.json found)")
    lines.extend(["", "## Laws and Rules", "", laws])
    return "\n".join(lines) + "\n"

def load(repo_root: Path, dry_run: bool = False) -> LoadReport:
    """Rebuild .claude/ and CLAUDE.md from the freeze."""
    written = []
    removed = []
    warnings = []

    try:
        freeze = load_freeze(repo_root)
    except Exception as e:
        return LoadReport(written=[], removed=[], warnings=[f"Failed to load freeze: {e}"])

    claude_dir = repo_root / ".claude"
    for folder in ("agents", "skills", "hooks"):
        target = claude_dir / folder
        if target.exists() and not dry_run:
            shutil.rmtree(target)
            removed.append(str(target))
        if not dry_run:
            target.mkdir(parents=True, exist_ok=True)

    catalog_dir = vash_root() / "catalog"

    for agent in freeze.data.get("agents", []):
        src = catalog_dir / "agents" / f"{agent['id']}.md"
        if src.exists():
            dst = claude_dir / "agents" / f"{agent['id']}.md"
            if not dry_run:
                shutil.copy2(src, dst)
            written.append(str(dst))
        else:
            warnings.append(f"Agent {agent['id']} not found in catalog")

    for skill in freeze.data.get("skills", []):
        src = catalog_dir / "skills" / skill['id']
        if src.exists():
            dst = claude_dir / "skills" / skill['id']
            if not dry_run:
                shutil.copytree(src, dst, dirs_exist_ok=True)
            written.append(str(dst))
        else:
            warnings.append(f"Skill {skill['id']} not found in catalog")

    hooks_src = catalog_dir / "hooks"
    if hooks_src.exists():
        for h in hooks_src.iterdir():
            if h.is_file():
                dst = claude_dir / "hooks" / h.name
                if not dry_run:
                    shutil.copy2(h, dst)
                    dst.chmod(dst.stat().st_mode | 0o111)
                written.append(str(dst))

    claude_md = repo_root / "CLAUDE.md"
    content = generate_claude_md(repo_root)
    if not dry_run:
        claude_md.write_text(content, encoding="utf-8", newline="\n")
    written.append(str(claude_md))

    from vash.loader.manifest import generate_manifest
    import json
    manifest = generate_manifest(repo_root)
    manifest_path = repo_root / "ai-manifest.json"
    if not dry_run:
        manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
    written.append(str(manifest_path))

    return LoadReport(written=written, removed=removed, warnings=warnings)
